-- 정책을 반복 적용할 때 발생할 이름 중복 방지
DROP POLICY IF EXISTS
    "Users can upload own club images"
ON storage.objects;

DROP POLICY IF EXISTS
    "Users can view own club images"
ON storage.objects;

DROP POLICY IF EXISTS
    "Users can update own club images"
ON storage.objects;

DROP POLICY IF EXISTS
    "Users can delete own club images"
ON storage.objects;

-- 자신의 UUID 폴더에만 업로드 가능
CREATE POLICY
    "Users can upload own club images"
ON storage.objects
FOR INSERT
TO authenticated
WITH CHECK (
    bucket_id = 'club-images'
    AND (storage.foldername(name))[1] =
        (SELECT auth.uid())::text
);

-- 자신의 UUID 폴더에 있는 객체 정보 조회 가능
CREATE POLICY
    "Users can view own club images"
ON storage.objects
FOR SELECT
TO authenticated
USING (
    bucket_id = 'club-images'
    AND (storage.foldername(name))[1] =
        (SELECT auth.uid())::text
);

-- 자신의 UUID 폴더에 있는 이미지 수정 가능
CREATE POLICY
    "Users can update own club images"
ON storage.objects
FOR UPDATE
TO authenticated
USING (
    bucket_id = 'club-images'
    AND (storage.foldername(name))[1] =
        (SELECT auth.uid())::text
)
WITH CHECK (
    bucket_id = 'club-images'
    AND (storage.foldername(name))[1] =
        (SELECT auth.uid())::text
);

-- 자신의 UUID 폴더에 있는 이미지 삭제 가능
CREATE POLICY
    "Users can delete own club images"
ON storage.objects
FOR DELETE
TO authenticated
USING (
    bucket_id = 'club-images'
    AND (storage.foldername(name))[1] =
        (SELECT auth.uid())::text
);

COMMIT;