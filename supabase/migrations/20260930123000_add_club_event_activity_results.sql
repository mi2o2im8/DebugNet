-- =========================================================
-- H4 회원 참여 저하 분석용 실제 활동 결과
--
-- event_participants.attendance_status는 일정 전 참석 의사이며,
-- 실제 출석 결과와 의미가 다르다. 두 값을 섞지 않도록
-- 운영자가 일정 종료 후 기록하는 별도 테이블을 사용한다.
-- =========================================================

CREATE TABLE IF NOT EXISTS
    public.club_event_activity_results
(
    activity_result_id bigint
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    event_id bigint NOT NULL,
    user_id uuid NOT NULL,

    result text NOT NULL,

    recorded_by_user_id uuid,
    recorded_at timestamp with time zone
        NOT NULL
        DEFAULT now(),

    created_at timestamp with time zone
        NOT NULL
        DEFAULT now(),

    CONSTRAINT
        club_event_activity_results_event_fkey
        FOREIGN KEY (event_id)
        REFERENCES public.club_events(event_id)
        ON DELETE CASCADE,

    CONSTRAINT
        club_event_activity_results_user_fkey
        FOREIGN KEY (user_id)
        REFERENCES public.users(user_id)
        ON DELETE CASCADE,

    CONSTRAINT
        club_event_activity_results_recorded_by_fkey
        FOREIGN KEY (recorded_by_user_id)
        REFERENCES public.users(user_id)
        ON DELETE SET NULL,

    CONSTRAINT
        club_event_activity_results_result_check
        CHECK (
            result IN (
                'attended',
                'cancelled',
                'no_show',
                'not_eligible'
            )
        ),

    CONSTRAINT
        club_event_activity_results_event_user_key
        UNIQUE (event_id, user_id)
);

ALTER TABLE public.club_event_activity_results
ENABLE ROW LEVEL SECURITY;

CREATE INDEX IF NOT EXISTS
    club_event_activity_results_user_event_idx
ON public.club_event_activity_results (
    user_id,
    event_id
);

COMMENT ON TABLE
    public.club_event_activity_results
IS
    '일정 종료 후 운영자가 기록하는 회원별 실제 활동 결과';

COMMENT ON COLUMN
    public.club_event_activity_results.result
IS
    'attended=실제 참석, cancelled=사전 취소, no_show=노쇼, not_eligible=참여 대상 아님';
