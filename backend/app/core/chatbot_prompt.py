def build_system_prompt() -> str:
    """LLM에 전달할 시스템 프롬프트를 만든다."""

    allowed_actions = "\n".join(
        f"- {path} : {label}"
        for path, label in ALLOWED_ACTIONS.items()
    )

    return (
        SYSTEM_PROMPT_TEMPLATE
        .replace("{service_guide}", SERVICE_GUIDE)
        .replace("{allowed_actions}", allowed_actions)
    )


