# ⭐ LLM 기본 응답
# =========================================================

# LLM 응답이 잘못된 형식이거나 답변을 만들지 못했을 때 사용한다.

FALLBACK_REPLY = {
    "answer": "지금은 답변을 준비하지 못했어요. 자주 묻는 질문에서 찾아보거나 잠시 후 다시 물어봐주세요.",
    "steps": [],
    "actions": [],
    "found": False,
}


# =========================================================
# ⭐ LLM 응답 정리
# =========================================================

def parse_llm_reply(raw_text: str) -> dict:
    """LLM 응답을 화면에서 사용할 dict 형태로 변환한다."""

    text = (raw_text or "").strip()

    if not text:
        return dict(FALLBACK_REPLY)

    # ⭐ LLM이 JSON을 코드블록으로 감싸서 보내는 경우 제거
    if text.startswith("```"):
        lines = text.splitlines()

        if lines and lines[0].strip().startswith("```"):
            lines = lines[1:]

        if lines and lines[-1].strip() == "```":
            lines = lines[:-1]

        text = "\n".join(lines).strip()

    # ⭐ JSON 형식으로 변환
    try:
        data = json.loads(text)

    except (json.JSONDecodeError, TypeError):
        return dict(FALLBACK_REPLY)

    # ⭐ JSON이 객체가 아니면 기본 응답
    if not isinstance(data, dict):
        return dict(FALLBACK_REPLY)

    # ⭐ 답변 가져오기
    answer = str(data.get("answer") or "").strip()

    if not answer:
        return dict(FALLBACK_REPLY)

    # ⭐ 단계별 안내 정리
    steps = []

    for step in data.get("steps") or []:

        step = str(step).strip()

        if step:
            steps.append(step)

        if len(steps) == 4:
            break

    # ⭐ 최종 응답
    return {
        "answer": answer,
        "steps": steps,
        "actions": filter_actions(data.get("actions") or []),
        "found": bool(data.get("found", True)),
    }


# =========================================================
# ⭐ 바로가기 필터
# =========================================================

def filter_actions(actions) -> list:
    """허용된 화면 경로만 남기고 최대 2개까지 반환한다."""

    result = []

    for action in actions:

        # ⭐ action이 객체가 아니면 제외
        if not isinstance(action, dict):
            continue

        path = action.get("path")

        # ⭐ 허용되지 않은 경로는 제외
        if path not in ALLOWED_ACTIONS:
            continue

        # ⭐ label이 없으면 등록된 기본 이름 사용
        label = str(
            action.get("label") or ALLOWED_ACTIONS[path]
        ).strip()

        result.append({
            "label": label,
            "path": path,
        })

        # ⭐ 바로가기는 최대 2개
        if len(result) == 2:
            break

    return result