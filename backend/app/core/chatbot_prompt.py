# LLM은 이 경로를 만들지 않는다. chatbot_service가 운영 중인 동호회를
# 조회해서 채워 넣고, 여기 패턴에 맞는 경로만 통과시킨다.

DYNAMIC_ACTION_PATTERNS = [
    re.compile(r"^/clubs/\d+$"),
    re.compile(r"^/clubs/\d+/home$"),
    re.compile(r"^/clubs/\d+/manage$"),
    re.compile(r"^/clubs/\d+/manage/members$"),
    re.compile(r"^/clubs/\d+/manage/events$"),
    re.compile(r"^/clubs/\d+/manage/events/new$"),
    re.compile(r"^/clubs/\d+/manage/community$"),
    re.compile(r"^/clubs/\d+/manage/community/write$"),
    re.compile(r"^/clubs/\d+/manage/settings$"),
    re.compile(r"^/clubs/\d+/manage/settings/join$"),
    re.compile(r"^/clubs/\d+/manage/settings/delete$"),
    re.compile(r"^/clubs/\d+/matches$"),
]


def is_allowed_path(path: str) -> bool:
    """고정 경로 또는 동호회별 경로 패턴에 맞으면 True"""

    if not isinstance(path, str):
        return False

    if path in ALLOWED_ACTIONS:
        return True

    return any(pattern.match(path) for pattern in DYNAMIC_ACTION_PATTERNS)


