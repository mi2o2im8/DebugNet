# =========================================================
# ⭐ 문장 정규화
# =========================================================
# 띄어쓰기/문장부호를 없애서 "가입 신청"과 "가입신청"을 같게 본다.

_STRIP_PATTERN = re.compile(r"[\s\?\!\.\,\~\-·…'\"“”‘’()\[\]]+")


def normalize(text: str) -> str:
    return _STRIP_PATTERN.sub("", (text or "").lower())


# =========================================================
# ⭐ 운영진 질문 신호
# =========================================================
# 같은 점수라면 "우리 동호회", "운영" 같은 단어가 있을 때 운영진 답변을 우선한다.

_OPERATOR_HINTS = (
    "우리동호회", "운영진", "운영자", "동호회장", "회장", "관리자", "운영중",
    "운영하는", "내가만든", "우리클럽", "우리모임",
)


def _pattern_score(pattern: tuple[str, ...] | str, text: str) -> int:
    """패턴의 모든 토큰이 들어 있으면 점수, 아니면 0"""

    # ("가입하려") 처럼 쉼표를 빠뜨린 한 단어 패턴도 안전하게 처리
    if isinstance(pattern, str):
        pattern = (pattern,)

    tokens = [normalize(token) for token in pattern]

    if not all(token and token in text for token in tokens):
        return 0

    # 긴 토큰, 여러 토큰이 동시에 맞을수록 구체적인 질문이다.
    return sum(len(token) for token in tokens) + 2 * (len(tokens) - 1)


# 이 점수보다 낮으면 규칙 답변을 쓰지 않고 LLM에게 넘긴다.
MIN_SCORE = 2


def match_intent(text: str) -> tuple[dict[str, Any] | None, int]:
    """
    가장 잘 맞는 의도와 점수를 돌려준다.
    못 찾으면 (None, 0)
    """

    normalized = normalize(text)

    if not normalized:
        return None, 0

    has_operator_hint = any(hint in normalized for hint in _OPERATOR_HINTS)

    best_intent = None
    best_score = 0

    for intent in INTENTS:

        score = max(
            (_pattern_score(pattern, normalized) for pattern in intent["patterns"]),
            default=0,
        )

        if score <= 0:
            continue

        # 운영진 신호가 있으면 운영진 의도에 가산점
        if has_operator_hint and intent["role"] == "operator":
            score += 3

        if score > best_score:
            best_score = score
            best_intent = intent

    if best_score < MIN_SCORE:
        return None, 0

    return best_intent, best_score


def get_intent(intent_id: str) -> dict[str, Any] | None:
    return _INTENT_BY_ID.get(intent_id)


